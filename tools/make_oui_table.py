#!/usr/bin/env python3
"""Build firmware/phase2-xiao-sniffer/oui_table.h from the IEEE MAC vendor list.

The first 3 bytes of a MAC address (the OUI) say which company made the radio.
This script keeps only the makers that matter for finding hidden devices:

  CAM = camera / doorbell / security brands
  IOT = Wi-Fi chip makers found inside cheap cameras, smart plugs and "spy" gadgets

Run it again any time to refresh the list (needs internet):
    python3 tools/make_oui_table.py            # downloads oui.csv from IEEE
    python3 tools/make_oui_table.py oui.csv    # or use a copy you already have
"""
import csv
import io
import pathlib
import re
import sys
import urllib.request

IEEE_URL = "https://standards-oui.ieee.org/oui/oui.csv"
OUT = pathlib.Path(__file__).resolve().parent.parent / "firmware/phase2-xiao-sniffer/oui_table.h"

# (category, short label shown on screen, regex matched against the IEEE organization name)
RULES = [
    ("CAM", "Hikvision", r"hikvision"),
    ("CAM", "Dahua", r"dahua"),
    ("CAM", "Wyze", r"\bwyze\b"),
    ("CAM", "Reolink", r"reolink"),
    ("CAM", "Amcrest", r"amcrest"),
    ("CAM", "Ring", r"^ring llc"),
    ("CAM", "Arlo", r"^arlo technolog"),
    ("CAM", "EZVIZ", r"ezviz"),
    ("CAM", "Xiaoyi/YI", r"xiaoyi"),
    ("CAM", "Axis", r"^axis communications"),
    ("CAM", "Uniview", r"uniview"),
    ("CAM", "Lorex", r"\blorex\b"),
    ("CAM", "Swann", r"\bswann\b"),
    ("CAM", "Nest", r"^nest labs"),
    ("CAM", "Canary", r"^canary connect"),
    ("CAM", "Vivint", r"\bvivint\b"),
    ("CAM", "SimpliSafe", r"simplisafe"),
    ("CAM", "Zmodo", r"zmodo"),
    ("IOT", "Tuya", r"\btuya\b"),
    ("IOT", "Espressif", r"espressif"),
    ("IOT", "Beken", r"\bbeken\b"),
    ("IOT", "Bouffalo", r"bouffalo"),
    ("IOT", "AltoBeam", r"altobeam"),
    ("IOT", "Bilian", r"\bbilian\b"),
    ("IOT", "Fn-Link", r"fn-link"),
    ("IOT", "Ingenic", r"\bingenic\b"),
]


def load_rows(path=None):
    if path:
        data = pathlib.Path(path).read_text(encoding="utf-8", errors="replace")
    else:
        req = urllib.request.Request(IEEE_URL, headers={"User-Agent": "Mozilla/5.0"})
        data = urllib.request.urlopen(req, timeout=120).read().decode("utf-8", errors="replace")
    return list(csv.DictReader(io.StringIO(data)))


def main():
    rows = load_rows(sys.argv[1] if len(sys.argv) > 1 else None)
    labels = []
    entries = {}
    report = {}
    for cat, label, pat in RULES:
        rx = re.compile(pat, re.I)
        if label not in labels:
            labels.append(label)
        li = labels.index(label)
        for r in rows:
            if r.get("Registry") != "MA-L":
                continue
            if rx.search(r["Organization Name"]):
                oui = int(r["Assignment"], 16)
                entries[oui] = (1 if cat == "CAM" else 2, li)
                report.setdefault(label, set()).add(r["Organization Name"].strip())

    lines = [
        "// oui_table.h - GENERATED by tools/make_oui_table.py from the IEEE MA-L list. Do not edit by hand.",
        f"// {len(entries)} entries. Category 1 = camera/security brand, 2 = IoT Wi-Fi chip maker.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct OuiEntry { uint32_t oui; uint8_t cat; uint8_t label; };",
        "",
        "static const char *const OUI_LABELS[] = {",
    ]
    lines += [f'  "{l}",' for l in labels]
    lines += ["};", "", "static const OuiEntry OUI_TABLE[] = {"]
    for oui in sorted(entries):
        cat, li = entries[oui]
        lines.append(f"  {{0x{oui:06X}, {cat}, {li}}},")
    lines += ["};", f"static const uint16_t OUI_COUNT = {len(entries)};", ""]
    OUT.write_text("\n".join(lines))

    print(f"wrote {OUT} ({len(entries)} entries)")
    for label in labels:
        names = sorted(report.get(label, []))
        print(f"  {label:12s} {sum(1 for v in entries.values() if labels[v[1]] == label):4d}  {'; '.join(names)[:150]}")


if __name__ == "__main__":
    main()
